function flat(obj, prefix = '') {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'object' && v) Object.assign(out, flat(v, path));
    else out[path] = v;
  }
  return out;
}

